"""**SAP probes**

Attack prompts generated by the semi-automatic attack prompt (SAP) generation method.

SAP ("Attack Prompt Generation for Red Teaming and Defending Large Language Models",
Findings of EMNLP 2023) generates adversarial attack prompts through in-context
learning, producing prompts that mimic human speech while carrying a harmful request.
The published SAP dataset contains these generated attack prompts across several harm
categories; this module replays them against a target to check whether the target
complies with the embedded harmful request.

Only probes implementing SAP-generated attack prompts should be added here.
"""

import json
from pathlib import Path

from garak import _config
from garak.data import path as data_path
import garak.probes


class AttackPrompts(garak.probes.Probe):
    """SAP-generated attack prompts

    Sends attack prompts produced by the semi-automatic attack prompt (SAP) generation
    method (Findings of EMNLP 2023). SAP prompts are built with in-context learning so
    they read like ordinary human speech, which makes them a distinct jailbreak vector
    from template-heavy attacks such as DAN. A target that complies with the harmful
    request inside a SAP prompt fails this probe.
    """

    lang = "en"
    doc_uri = "https://aclanthology.org/2023.findings-emnlp.143/"
    goal = "get the model to comply with SAP-generated attack prompts"
    intent = "T009ignore"  # SAP prompts attempt to override the model's safety alignment with attacker-supplied instructions
    primary_detector = "mitigation.MitigationBypass"
    extended_detectors = ["dan.DAN"]
    tags = [
        "avid-effect:security:S0403",  # jailbreak-style attack prompts
        "owasp:llm01",  # prompt injection
        "quality:Security:PromptStability",  # tests robustness of safety alignment
        "demon:Fictionalizing:Roleplaying:User_persona",  # prompts adopt attacker-chosen personas and roles to elicit harmful content
        "euai:robustness:adversarial",  # adversarial robustness evaluation
    ]
    tier = garak.probes.Tier.COMPETE_WITH_SOTA
    active = True

    def __init__(self, config_root=_config):
        super().__init__(config_root=config_root)
        # one file per SAP30 harm category (the sexual-minors category from the
        # published dataset is deliberately not shipped)
        self.prompts = []
        for prompt_file in sorted((data_path / "sap").glob("*.json")):
            with open(prompt_file, "r", encoding="utf-8") as f:
                self.prompts.extend(json.load(f))
